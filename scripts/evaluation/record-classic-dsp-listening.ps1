[CmdletBinding()]
param(
  [string]$WorkspaceRoot = '.local-evaluation\classic-dsp',

  [Parameter(Mandatory = $true)]
  [ValidateNotNullOrEmpty()]
  [string]$Evidence,

  [Parameter(Mandatory = $true)]
  [ValidateSet('accepted', 'rejected')]
  [string]$Decision,

  [Parameter(Mandatory = $true)]
  [ValidateNotNullOrEmpty()]
  [string]$MusicPreservation,

  [Parameter(Mandatory = $true)]
  [ValidateNotNullOrEmpty()]
  [string]$Balanced,

  [string]$Strong = '',

  [Parameter(Mandatory = $true)]
  [ValidateNotNullOrEmpty()]
  [string]$ReviewMethod,

  [string]$Notes = '',
  [switch]$Force
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function Resolve-EvidencePath {
  param(
    [Parameter(Mandatory = $true)][string]$Workspace,
    [Parameter(Mandatory = $true)][string]$RequestedPath
  )

  $measurementRoot = [IO.Path]::GetFullPath((Join-Path $Workspace 'measurements'))
  $evidencePath = [IO.Path]::GetFullPath($RequestedPath)
  $prefix = $measurementRoot.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar

  if (-not $evidencePath.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
    throw "Evidence path must remain under $measurementRoot."
  }
  if ([IO.Path]::GetExtension($evidencePath) -ne '.json') {
    throw 'Evidence path must be a JSON file.'
  }
  if (-not (Test-Path $evidencePath -PathType Leaf)) {
    throw "Evidence file was not found: $evidencePath"
  }

  return $evidencePath
}

function Set-JsonProperty {
  param(
    [Parameter(Mandatory = $true)]$Object,
    [Parameter(Mandatory = $true)][string]$Name,
    $Value
  )
  $Object | Add-Member -NotePropertyName $Name -NotePropertyValue $Value -Force
}

function Write-JsonAtomic {
  param(
    [Parameter(Mandatory = $true)][string]$Path,
    [Parameter(Mandatory = $true)]$Value
  )

  $tempPath = "$Path.tmp"
  if (Test-Path $tempPath -PathType Leaf) {
    Remove-Item $tempPath -Force
  }

  try {
    $json = $Value | ConvertTo-Json -Depth 20
    [IO.File]::WriteAllText($tempPath, $json + [Environment]::NewLine, [Text.UTF8Encoding]::new($false))
    [IO.File]::Replace($tempPath, $Path, $null)
  }
  finally {
    if (Test-Path $tempPath -PathType Leaf) {
      Remove-Item $tempPath -Force
    }
  }
}

$workspace = [IO.Path]::GetFullPath($WorkspaceRoot)
$evidencePath = Resolve-EvidencePath -Workspace $workspace -RequestedPath $Evidence
$data = Get-Content -LiteralPath $evidencePath -Raw | ConvertFrom-Json

if ($data.objectiveStatus -ne 'rendered' -or -not $data.renders -or
    -not $data.renders.musicPreservation -or -not $data.renders.balanced -or
    -not $data.subjectiveReview) {
  throw 'The selected file is not Classic DSP render evidence generated by render-classic-dsp-fixture.ps1.'
}

if ($data.subjectiveReview.status -eq 'complete' -and -not $Force) {
  throw 'Subjective review is already complete. Use -Force to replace the recorded review.'
}

$data.subjectiveReview.status = 'complete'
$data.subjectiveReview.musicPreservation = $MusicPreservation
$data.subjectiveReview.balanced = $Balanced
$data.subjectiveReview.strong = $Strong
$data.subjectiveReview.notes = $Notes
Set-JsonProperty -Object $data.subjectiveReview -Name 'decision' -Value $Decision
Set-JsonProperty -Object $data.subjectiveReview -Name 'reviewMethod' -Value $ReviewMethod
Set-JsonProperty -Object $data.subjectiveReview -Name 'reviewedAtUtc' -Value ([DateTime]::UtcNow.ToString('o'))

Write-JsonAtomic -Path $evidencePath -Value $data

Write-Host "Subjective review: complete ($Decision)"
Write-Host "Evidence: $evidencePath"
